#!/bin/sh
# Regenerate README.md in this directory from the front matter of every
# <TYPE>.md assessment beside it. Run from anywhere:
#
#   sh docs/wiki/alert-assessments/gen_index.sh
#
# The index is generated, never hand-edited: the front matter is the
# record and tests/test_alert_assessments.c checks it, so a table typed
# by hand would be a second copy free to drift. Each cell carries the
# verdict head of its field (the text before the first " - "); the full
# reasoning is one click away in the linked file.
#
# Front matter shape (enforced by the test): line 1 is "---", then one
# "key: value" per line, closed by "---".
set -eu

dir=$(cd "$(dirname "$0")" && pwd)
out="$dir/README.md"
tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT INT TERM HUP

# README.md is this script's output, not an assessment, and matches the glob.
n=$(ls "$dir"/[A-Z]*.md | grep -v '/README\.md$' | wc -l | tr -d ' ')

{
cat <<EOF
# Alert assessments

**Summary**: One research assessment per alert type: what the rule
actually checks (file:line), how its \`count\` accumulates, the mechanism
it detects, the evidence that proves or refutes a firing, benign causes,
a severity and false-positive judgement, and a noise verdict against the
reference-host firing data. Each file closes with its bibliography and
the notes of the pass that verified it against the tree and the sources.

**Sources**: the \`<TYPE>.md\` files in this directory (front matter);
\`include/sloth_alerts.def\`; \`src/alerts/\`.

**Last updated**: generated by \`gen_index.sh\` in this directory - do not
edit by hand.

Assessed: $n alert types. The alert types without a file yet are listed
in \`tests/test_alert_assessments.c\` (\`pending[]\`), which fails on any
type that is neither assessed nor listed there, and on a listed type that
has gained a file.

A fire count in the hundreds of millions is per-evaluation counting of a
standing condition (at least four polls a second), not that many events;
each file's \`count_semantics\` says how its rule counts.

| Type | Technique | Severity assessment | False-positive risk | Noise verdict |
|---|---|---|---|---|
EOF

for f in "$dir"/[A-Z]*.md; do
    [ "$(basename "$f")" = README.md ] && continue
    awk -v file="$(basename "$f")" '
        function head(v) {
            sub(/^[a-z_]+: */, "", v)
            i = index(v, " - ")
            if (i > 0) v = substr(v, 1, i - 1)
            gsub(/\|/, "\\|", v)
            return v
        }
        NR == 1 { if ($0 != "---") { bad = 1; exit } next }
        $0 == "---" { done = 1; exit }
        /^type: /                { ty = $0; sub(/^type: */, "", ty) }
        /^technique: /           { te = $0; sub(/^technique: */, "", te); gsub(/"/, "", te) }
        /^severity_assessment: / { sa = head($0) }
        /^false_positive_risk: / { fp = head($0) }
        /^noise_verdict: /       { nv = head($0) }
        END {
            if (bad || !done || ty == "") {
                print "gen_index: " file ": front matter unparsable" > "/dev/stderr"
                exit 1
            }
            if (te == "") te = "-"
            printf "| [%s](%s) | %s | %s | %s | %s |\n", ty, file, te, sa, fp, nv
        }
    ' "$f"
done

cat <<EOF

## Related pages

- [[alerts]] - the alert engine and its rules
- [[alert-remediation]] - how to investigate and fix each alert type
- [[research-corpus]] - the cited source documents every detector rests on
EOF
} > "$tmp"

mv "$tmp" "$out"
trap - EXIT INT TERM HUP
echo "gen_index: $n assessments -> $out"
