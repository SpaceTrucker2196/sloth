/*
 * Alert assessments — docs/wiki/alert-assessments/<TYPE>.md.
 *
 * One research file per alert type, written for the alert detail page:
 * what the rule checks, how its count accumulates, the evidence that
 * proves or refutes a firing, a severity and noise verdict, and a
 * bibliography. A file that names the wrong rule, has lost its sources
 * or has no front matter a page can read is worse than none, because it
 * reads as authoritative. So each one is checked against the build:
 *
 *   - the front matter parses (line 1 "---", one "key: value" per line,
 *     closed by "---") and carries every field the page and the index
 *     read;
 *   - `type` is the file's own name and `technique` is what
 *     alert_technique() returns, so the file cannot describe a
 *     different row of include/sloth_alerts.def;
 *   - `rule_file` is "path:line ..." and that line of that file exists
 *     and contains "rule_" — the rule moving without the file following
 *     is the drift this catches;
 *   - `## Bibliography` has at least one numbered entry;
 *   - README.md (generated by gen_index.sh) has a row for it.
 *
 * Coverage is every ALERT_TYPE_* the compiled table knows, except the
 * types in pending[] below, which have no assessment yet. The list is
 * exact in both directions: a type neither assessed nor pending fails
 * (a new rule needs its file or an explicit entry here), and a pending
 * type that has gained a file fails until it is removed from the list,
 * so the list can only shrink honestly.
 */

#define AA_DIR      "docs/wiki/alert-assessments"
#define AA_KEY_LEN  32
#define AA_VAL_LEN  2048
#define AA_MAX_KEYS 16

/* Types with no assessment file yet, in sloth_alerts.def order. */
static const char *const pending[] = {
    "LDAP_SEARCH_FLOOD", "BGP_NOTIFICATION_BURST", "SSH_BRUTE_FORCE",
    "RDP_BRUTE_FORCE", "SNMP_COMMUNITY_BRUTE", "MQTT_BROKER_BRUTE",
    "ATTACK_PATH", "WEAK_TLS", "NO_MONITOR_MODE", "CLEARTEXT_CRED",
    "BEACON_FLOOD", "AUTH_FLOOD", "FRAG_AMSDU_EAPOL", "FRAG_MIXKEY",
    "FRAG_PN_GAP", "FRAG_EAPOL_RELAY", "SA_QUERY_FLOOD", "MFP_UNPROTECTED",
};
#define AA_PENDING_N ((int)(sizeof(pending) / sizeof(pending[0])))

/* Fields every assessment carries; the index and the alert page read
 * them by name. */
static const char *const required_keys[] = {
    "type", "technique", "rule_file", "count_semantics",
    "severity_assessment", "false_positive_risk", "noise_verdict",
    "prevalence", "tuning", "researched",
};
#define AA_REQ_N ((int)(sizeof(required_keys) / sizeof(required_keys[0])))

typedef struct {
    int  n;
    char key[AA_MAX_KEYS][AA_KEY_LEN];
    char val[AA_MAX_KEYS][AA_VAL_LEN];
} aa_fm_t;

static char *aa_slurp(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long n = ftell(f);
    if (n < 0) { fclose(f); return NULL; }
    rewind(f);
    char *buf = malloc((size_t)n + 1);
    if (!buf) { fclose(f); return NULL; }
    size_t got = fread(buf, 1, (size_t)n, f);
    buf[got] = '\0';
    fclose(f);
    return buf;
}

/* Parse the front matter of `t`. Returns the byte offset just past the
 * closing "---" line, or -1 if it is absent, unterminated, has a line
 * that is not "key: value", repeats a key or overflows the table. */
static long aa_front_matter(const char *t, aa_fm_t *fm) {
    memset(fm, 0, sizeof(*fm));
    if (strncmp(t, "---\n", 4) != 0) return -1;
    const char *p = t + 4;
    while (*p) {
        const char *nl = strchr(p, '\n');
        size_t len = nl ? (size_t)(nl - p) : strlen(p);
        if (len == 3 && !strncmp(p, "---", 3))
            return (long)((nl ? nl + 1 : p + len) - t);
        size_t k = 0;
        while (k < len && (islower((unsigned char)p[k]) || p[k] == '_')) k++;
        if (k == 0 || k >= AA_KEY_LEN || k + 1 >= len ||
            p[k] != ':' || p[k + 1] != ' ')
            return -1;
        if (fm->n >= AA_MAX_KEYS) return -1;
        for (int i = 0; i < fm->n; i++)
            if (strlen(fm->key[i]) == k && !strncmp(fm->key[i], p, k))
                return -1;
        memcpy(fm->key[fm->n], p, k);
        fm->key[fm->n][k] = '\0';
        size_t vl = len - k - 2;
        if (vl >= AA_VAL_LEN) vl = AA_VAL_LEN - 1;
        memcpy(fm->val[fm->n], p + k + 2, vl);
        fm->val[fm->n][vl] = '\0';
        fm->n++;
        if (!nl) break;
        p = nl + 1;
    }
    return -1;
}

static const char *aa_get(const aa_fm_t *fm, const char *key) {
    for (int i = 0; i < fm->n; i++)
        if (!strcmp(fm->key[i], key)) return fm->val[i];
    return NULL;
}

/* Split "path:line rest" into path and line. Returns 0 on a well-formed
 * value: a relative path with no "..", a positive line number, then end
 * or a space. */
static int aa_rule_file(const char *v, char *path, size_t psz, long *line) {
    const char *c = strchr(v, ':');
    if (!c || c == v || (size_t)(c - v) >= psz) return -1;
    memcpy(path, v, (size_t)(c - v));
    path[c - v] = '\0';
    if (path[0] == '/' || strstr(path, "..")) return -1;
    const char *d = c + 1;
    if (!isdigit((unsigned char)*d)) return -1;
    long n = 0;
    while (isdigit((unsigned char)*d)) {
        n = n * 10 + (*d - '0');
        if (n > 1000000) return -1;
        d++;
    }
    if (n <= 0 || (*d != '\0' && *d != ' ')) return -1;
    *line = n;
    return 0;
}

/* Copy line `n` (1-based) of `path` into `out`. Returns 0 if it exists. */
static int aa_file_line(const char *path, long n, char *out, size_t osz) {
    char *t = aa_slurp(path);
    if (!t) return -1;
    const char *p = t;
    for (long i = 1; i < n && p; i++) {
        p = strchr(p, '\n');
        if (p) p++;
    }
    int rc = -1;
    if (p && *p) {
        const char *nl = strchr(p, '\n');
        size_t len = nl ? (size_t)(nl - p) : strlen(p);
        if (len >= osz) len = osz - 1;
        memcpy(out, p, len);
        out[len] = '\0';
        rc = 0;
    }
    free(t);
    return rc;
}

/* Numbered entries ("1. ...") under "## Bibliography", up to the next
 * "## " heading. -1 when the section is missing. */
static int aa_bib_entries(const char *t) {
    const char *p = strstr(t, "\n## Bibliography\n");
    if (!p) return -1;
    p += strlen("\n## Bibliography\n");
    int n = 0;
    while (p && *p) {
        if (!strncmp(p, "## ", 3)) break;
        const char *q = p;
        while (isdigit((unsigned char)*q)) q++;
        if (q > p && q[0] == '.' && q[1] == ' ' && q[2] && q[2] != '\n') n++;
        p = strchr(p, '\n');
        if (p) p++;
    }
    return n;
}

static int aa_is_pending(const char *name) {
    for (int i = 0; i < AA_PENDING_N; i++)
        if (!strcmp(pending[i], name)) return 1;
    return 0;
}

/* ── the parsers, on fixed text ── */

static void test_front_matter_parser(void) {
    aa_fm_t fm;
    const char *ok = "---\ntype: X\ntechnique: \"\"\n---\nbody\n";
    long off = aa_front_matter(ok, &fm);
    ASSERT(off > 0);
    ASSERT_STR(ok + off, "body\n");
    ASSERT_EQ(fm.n, 2);
    ASSERT_STR(aa_get(&fm, "type"), "X");
    ASSERT_STR(aa_get(&fm, "technique"), "\"\"");
    ASSERT(aa_get(&fm, "rule_file") == NULL);
    /* Absent, unterminated, a non key: value line, a repeated key. */
    ASSERT_EQ(aa_front_matter("type: X\n---\n", &fm), -1);
    ASSERT_EQ(aa_front_matter("---\ntype: X\n", &fm), -1);
    ASSERT_EQ(aa_front_matter("---\ntype: X\nprose here\n---\n", &fm), -1);
    ASSERT_EQ(aa_front_matter("---\nType: X\n---\n", &fm), -1);
    ASSERT_EQ(aa_front_matter("---\ntype: X\ntype: Y\n---\n", &fm), -1);
}

static void test_rule_file_parser(void) {
    char path[256];
    long line = 0;
    ASSERT_EQ(aa_rule_file("src/alerts/rules_wired.c:121 rule_arp_spoof()",
                           path, sizeof(path), &line), 0);
    ASSERT_STR(path, "src/alerts/rules_wired.c");
    ASSERT_EQ(line, 121);
    ASSERT_EQ(aa_rule_file("src/a.c:7", path, sizeof(path), &line), 0);
    ASSERT_EQ(line, 7);
    ASSERT_EQ(aa_rule_file("src/a.c", path, sizeof(path), &line), -1);
    ASSERT_EQ(aa_rule_file("src/a.c:0", path, sizeof(path), &line), -1);
    ASSERT_EQ(aa_rule_file("src/a.c:12x", path, sizeof(path), &line), -1);
    ASSERT_EQ(aa_rule_file("/etc/passwd:1", path, sizeof(path), &line), -1);
    ASSERT_EQ(aa_rule_file("../x.c:1", path, sizeof(path), &line), -1);
}

static void test_bibliography_counter(void) {
    ASSERT_EQ(aa_bib_entries("x\n## Bibliography\n\n1. a\n2. b\n"), 2);
    /* Entries after the next heading are another section's. */
    ASSERT_EQ(aa_bib_entries("x\n## Bibliography\n1. a\n## Notes\n2. b\n"), 1);
    ASSERT_EQ(aa_bib_entries("x\n## Bibliography\n\nnone yet\n"), 0);
    ASSERT_EQ(aa_bib_entries("x\n## Bibliography\n1. \n"), 0);
    ASSERT_EQ(aa_bib_entries("x\n## Sources\n1. a\n"), -1);
}

/* ── the corpus ── */

static void test_every_alert_type_is_assessed(void) {
    char *index = aa_slurp(AA_DIR "/README.md");
    ASSERT(index != NULL);
    int assessed = 0, missing = 0, pending_seen = 0;
    for (int ty = 0; ty < (int)ALERT_TYPE_COUNT; ty++) {
        const char *full = alert_type_name((alert_type_t)ty);
        int named = strncmp(full, "ALERT_TYPE_", 11) == 0;
        ASSERT(named);
        if (!named) continue;
        const char *name = full + 11;
        char path[256];
        snprintf(path, sizeof(path), AA_DIR "/%.64s.md", name);
        char *t = aa_slurp(path);
        int pend = aa_is_pending(name);
        if (pend) pending_seen++;
        if (!t) {
            if (!pend) {
                missing++;
                fprintf(stderr, "    %s: no assessment and not in "
                                "pending[]\n", path);
            }
            continue;
        }
        if (pend)
            fprintf(stderr, "    %s exists: remove %s from pending[]\n",
                    path, name);
        ASSERT(!pend);
        assessed++;

        aa_fm_t fm;
        long off = aa_front_matter(t, &fm);
        if (off < 0)
            fprintf(stderr, "    %s: front matter does not parse\n", path);
        ASSERT(off > 0);
        for (int k = 0; k < AA_REQ_N; k++) {
            int has = aa_get(&fm, required_keys[k]) != NULL;
            if (!has)
                fprintf(stderr, "    %s: front matter has no %s\n",
                        path, required_keys[k]);
            ASSERT(has);
        }

        const char *v = aa_get(&fm, "type");
        int self = v && !strcmp(v, name);
        if (!self) fprintf(stderr, "    %s: type is not %s\n", path, name);
        ASSERT(self);

        /* "" in the file is the empty technique, as in the .def. */
        v = aa_get(&fm, "technique");
        const char *want = alert_technique((alert_type_t)ty);
        int tech = v && (!strcmp(v, want) ||
                         (!want[0] && !strcmp(v, "\"\"")));
        if (!tech)
            fprintf(stderr, "    %s: technique %s, alert_technique() "
                            "says \"%s\"\n", path, v ? v : "(none)", want);
        ASSERT(tech);

        v = aa_get(&fm, "rule_file");
        char rpath[256], text[512];
        long line = 0;
        int ok = v && aa_rule_file(v, rpath, sizeof(rpath), &line) == 0 &&
                 aa_file_line(rpath, line, text, sizeof(text)) == 0 &&
                 strstr(text, "rule_") != NULL;
        if (!ok)
            fprintf(stderr, "    %s: rule_file \"%.120s\" is not a line "
                            "containing rule_\n", path, v ? v : "(none)");
        ASSERT(ok);

        int bib = aa_bib_entries(t + (off > 0 ? off : 0));
        if (bib < 1)
            fprintf(stderr, "    %s: Bibliography has no entry\n", path);
        ASSERT_GE(bib, 1);

        char row[160];
        snprintf(row, sizeof(row), "| [%.64s](%.64s.md) |", name, name);
        int indexed = index && strstr(index, row) != NULL;
        if (!indexed)
            fprintf(stderr, "    %s/README.md has no row for %s; run "
                            "gen_index.sh\n", AA_DIR, name);
        ASSERT(indexed);
        free(t);
    }
    free(index);
    ASSERT_EQ(missing, 0);
    /* Every pending[] entry is a real type: a renamed or misspelt one
     * would otherwise excuse nothing and hide nothing, silently. */
    ASSERT_EQ(pending_seen, AA_PENDING_N);
    ASSERT_EQ(assessed + AA_PENDING_N, (int)ALERT_TYPE_COUNT);
    /* Floor: a wrong directory finds no files, and then every type
     * would have to be pending — which the line above already rejects
     * unless pending[] grew to match. */
    ASSERT_GE(assessed, 72);
}

void run_alert_assessment_tests(void) {
    TEST_SUITE("alert assessments (docs/wiki/alert-assessments)");
    RUN_TEST(test_front_matter_parser);
    RUN_TEST(test_rule_file_parser);
    RUN_TEST(test_bibliography_counter);
    RUN_TEST(test_every_alert_type_is_assessed);
}
