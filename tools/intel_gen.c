/* intel_gen: sloth's generator for its vendored intelligence packs
 * (#231, Stage 2 of #184). Build time only; reads the paths it is given
 * and nothing else, never the network.
 *
 *   intel_gen gen  INTEL_DIR OUT_DIR
 *       Verify the six packs and intel/LOCK (intel_read.h says what is
 *       checked), then write one initialiser file per sloth array into
 *       OUT_DIR, the rows only; the array definitions stay in src/ and
 *       #include them. A file is rewritten only when its bytes change,
 *       so a rebuilt generator does not recompile the tables.
 *
 *         oui_builtin.inc            g_oui                    src/oui.c
 *         attacker_hak5.inc          kHak5Ouis                src/wifi_oui_attacker.c
 *         attacker_espressif.inc     kEspressifOuis           src/wifi_oui_attacker.c
 *         camera_oui.inc             g_cam_oui                src/camera_vendor.c
 *         camera_server_brands.inc   g_cam_server_brands      src/camera_vendor.c
 *         camera_services.inc        g_cam_svcs               src/camera_vendor.c
 *         camera_setup_ssids.inc     g_camera_setup_ssid_pats src/camera_vendor.c
 *         surveillance_endpoints.inc kEndpoints               src/vendor_watchlist.c
 *         tool_signatures.inc        TOOL_SIGNATURES, less its terminator
 *                                                             src/tool_fingerprint.c
 *         ble_watchlist.inc          g_pack_rows, less its terminator
 *                                                             src/ble_watchlist.c
 *         intel_pack.inc             the version and hash     src/intel_pack.c
 *
 *   intel_gen lock INTEL_DIR VERSION COMMIT DATE
 *       Verify and parse the six packs as `gen` does, then write
 *       INTEL_DIR/LOCK naming VERSION, the snapshot hash, the comint
 *       COMMIT it came from and DATE. `make update-intel` runs it.
 *
 * Exit 0, or 1 with the reason on stderr and nothing written. */
#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "intel_read.h"

static char *g_buf;
static size_t g_len, g_cap;

static void out(const char *fmt, ...) {
    va_list ap;
    for (;;) {
        va_start(ap, fmt);
        int n = vsnprintf(g_buf ? g_buf + g_len : NULL, g_buf ? g_cap - g_len : 0, fmt, ap);
        va_end(ap);
        if (n < 0) { fprintf(stderr, "intel_gen: format error\n"); exit(1); }
        if (g_buf && g_len + (size_t)n < g_cap) { g_len += (size_t)n; return; }
        size_t nc = g_cap ? g_cap * 2 : 1 << 16;
        while (nc < g_len + (size_t)n + 1) nc *= 2;
        char *nb = realloc(g_buf, nc);
        if (!nb) { fprintf(stderr, "intel_gen: out of memory\n"); exit(1); }
        g_buf = nb;
        g_cap = nc;
    }
}

/* A C string literal of s: printable ASCII as itself except '"', '\\'
 * and '?' (no trigraph can form), every other byte as a three-digit
 * octal escape, so the compiled bytes are the CSV's bytes exactly. */
static void cstr(const char *s) {
    out("\"");
    for (size_t i = 0; s[i]; i++) {
        unsigned char c = (unsigned char)s[i];
        switch (c) {
        case '"':  out("\\\""); break;
        case '\\': out("\\\\"); break;
        case '?':  out("\\?");  break;
        default:
            if (c < 0x20 || c > 0x7E) out("\\%03o", (unsigned)c);
            else out("%c", (int)c);
        }
    }
    out("\"");
}

static void head(const ir_snapshot_t *s, int pack, const char *file,
                 const char *array, const char *src) {
    const ir_file_t *f = NULL;
    for (int i = 0; i < s->man[pack].nfiles; i++)
        if (!strcmp(s->man[pack].files[i].path, file)) f = &s->man[pack].files[i];
    out("/* Generated by tools/intel_gen from intel/%s/%s\n", ir_pack_names[pack], file);
    out(" * (pack %s %s, sha256 %s).\n", ir_pack_names[pack],
        s->man[pack].pack_version, f ? f->sha256 : "?");
    out(" * The rows of %s in %s. Build output: never\n", array, src);
    out(" * edited, never committed; `make update-intel` changes the source. */\n");
}

static int write_if_changed(const char *dir, const char *name) {
    char path[4096], tmp[4200];
    snprintf(path, sizeof(path), "%s/%s", dir, name);
    FILE *f = fopen(path, "rb");
    if (f) {
        char *old = malloc(g_len + 1);
        size_t n = old ? fread(old, 1, g_len + 1, f) : 0;
        fclose(f);
        int same = old && n == g_len && memcmp(old, g_buf, g_len) == 0;
        free(old);
        if (same) { g_len = 0; return 0; }
    }
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    f = fopen(tmp, "wb");
    if (!f) { fprintf(stderr, "intel_gen: %s: %s\n", tmp, strerror(errno)); return -1; }
    int ok = fwrite(g_buf, 1, g_len, f) == g_len;
    if (fclose(f) != 0) ok = 0;
    if (!ok || rename(tmp, path) != 0) {
        fprintf(stderr, "intel_gen: cannot write %s\n", path);
        remove(tmp);
        return -1;
    }
    g_len = 0;
    return 0;
}

/* A flag mask as its AP_FP_FLAG_* names in bit order, or 0 (the reader
 * refused any bit without a name). */
static void flags(unsigned bits) {
    const char *sep = "";
    for (int i = 0; i < ir_flag_names_n; i++) {
        if (!((bits >> i) & 1u)) continue;
        out("%s%s", sep, ir_flag_names[i].name);
        sep = " | ";
    }
    if (!sep[0]) out("0");
}

static int gen(const ir_snapshot_t *s, const ir_lock_t *l, const char *dir) {
    int rc = 0;
    if (g_buf) g_buf[0] = '\0';
    g_len = 0;

    head(s, 3, "oui_builtin.csv", "g_oui", "src/oui.c");
    /* One row per line in this shape: slothweb's fallback vendor table
     * reads this file as text (web/tools/oui_csv.c, oui_build_sloth()). */
    for (int i = 0; i < s->n_oui; i++) {
        out("    { 0x%06lX, ", (unsigned long)s->oui[i].oui);
        cstr(s->oui[i].vendor);
        out(" },\n");
    }
    rc |= write_if_changed(dir, "oui_builtin.inc");

    for (int fam = 0; fam < 2; fam++) {
        head(s, 0, "attacker_ouis.csv", fam ? "kEspressifOuis" : "kHak5Ouis",
             "src/wifi_oui_attacker.c");
        for (int i = 0; i < s->n_att; i++) {
            if (s->att[i].family != fam) continue;
            out("    {0x%02x, 0x%02x, 0x%02x},", s->att[i].oui[0], s->att[i].oui[1],
                s->att[i].oui[2]);
            if (s->att[i].note[0]) {
                out("   /* ");
                /* Comment text: bytes as they are (validated: no
                 * delimiter, no control character). */
                out("%s", s->att[i].note);
                out(" */");
            }
            out("\n");
        }
        rc |= write_if_changed(dir, fam ? "attacker_espressif.inc" : "attacker_hak5.inc");
    }

    head(s, 2, "camera_vendors.csv", "g_cam_oui", "src/camera_vendor.c");
    for (int i = 0; i < s->n_cam; i++) {
        const ir_cam_oui_t *o = &s->cam[i];
        out("    { {0x%02X,0x%02X,0x%02X}, ", o->oui[0], o->oui[1], o->oui[2]);
        cstr(o->vendor); out(", "); cstr(o->org);
        out(", %d },\n", o->mixed);
    }
    rc |= write_if_changed(dir, "camera_oui.inc");

    head(s, 2, "camera_server_brands.csv", "g_cam_server_brands", "src/camera_vendor.c");
    for (int i = 0; i < s->n_brand; i++) { out("    "); cstr(s->brand[i]); out(",\n"); }
    rc |= write_if_changed(dir, "camera_server_brands.inc");

    head(s, 2, "camera_services.csv", "g_cam_svcs", "src/camera_vendor.c");
    for (int i = 0; i < s->n_svc; i++) {
        out("    { "); cstr(s->svc[i].name); out(", "); cstr(s->svc[i].label);
        out(", %d },\n", s->svc[i].camera_specific);
    }
    rc |= write_if_changed(dir, "camera_services.inc");

    head(s, 2, "camera_setup_ssids.csv", "g_camera_setup_ssid_pats", "src/camera_vendor.c");
    for (int i = 0; i < s->n_ssid; i++) {
        out("    { "); cstr(s->ssid[i].prefix); out(", "); cstr(s->ssid[i].label);
        out(", "); cstr(s->ssid[i].brand); out(" },\n");
    }
    rc |= write_if_changed(dir, "camera_setup_ssids.inc");

    head(s, 4, "surveillance_endpoints.csv", "kEndpoints", "src/vendor_watchlist.c");
    for (int i = 0; i < s->n_ep; i++) {
        out("    { "); cstr(s->ep[i].domain); out(", "); cstr(s->ep[i].vendor);
        out(", "); cstr(s->ep[i].family); out(" },\n");
    }
    rc |= write_if_changed(dir, "surveillance_endpoints.inc");

    head(s, 5, "tool_fingerprints.csv", "TOOL_SIGNATURES (less its terminator)",
         "src/tool_fingerprint.c");
    for (int i = 0; i < s->n_tool; i++) {
        const ir_tool_t *t = &s->tool[i];
        out("    { %s, 0x%08lXu, %u, 0x%08lXu,\n      ", ir_tool_names[t->tool].name,
            (unsigned long)t->vendor_ie_hash, (unsigned)t->beacon_interval_ms,
            (unsigned long)t->supported_rates);
        flags(t->require_flags); out(", "); flags(t->forbid_flags);
        out(", %u, %u, %u,\n      ", (unsigned)t->requires_karma_echo,
            (unsigned)t->requires_pmkid, (unsigned)t->unverified);
        cstr(t->human_label); out(",\n      ");
        cstr(t->evidence); out(",\n      ");
        cstr(t->id); out(", "); cstr(t->version); out(" },\n");
    }
    rc |= write_if_changed(dir, "tool_signatures.inc");

    head(s, 1, "ble_watchlist.csv", "g_pack_rows (less its terminator)", "src/ble_watchlist.c");
    if (s->n_ble == 0) out("/* no rows: the pack ships none */\n");
    for (int i = 0; i < s->n_ble; i++) {
        const ir_ble_t *w = &s->ble[i];
        out("    { "); cstr(w->category);
        out(", %s, 0x%04X, %d, %d, %d, ",
            w->match == 1 ? "BLE_WL_MFR" : w->match == 2 ? "BLE_WL_SVC_DATA" : "BLE_WL_UUID16",
            (unsigned)w->id, (int)w->subtype, (int)w->min_len, (int)w->max_len);
        cstr(w->source); out(" },\n");
    }
    rc |= write_if_changed(dir, "ble_watchlist.inc");

    out("/* Generated by tools/intel_gen from intel/LOCK and the six packs'\n");
    out(" * manifests: the snapshot these tables were built from, as\n");
    out(" * `intel_pack` reports it (src/intel_pack.h). */\n");
    out("#define SLOTH_INTEL_PACK_VERSION \"%s\"\n", l->pack_version);
    out("#define SLOTH_INTEL_PACK_HASH \"%s\"\n", s->hash);
    rc |= write_if_changed(dir, "intel_pack.inc");
    return rc ? -1 : 0;
}

static int read_lock(const char *intel_dir, ir_lock_t *l) {
    char path[4096], err[IR_ERR];
    snprintf(path, sizeof(path), "%s/LOCK", intel_dir);
    size_t n;
    char *b = ir_slurp(path, 1 << 16, &n, err, sizeof(err));
    if (!b) { fprintf(stderr, "intel_gen: %s\n", err); return -1; }
    int rc = ir_lock_parse(b, n, l, err, sizeof(err));
    free(b);
    if (rc) fprintf(stderr, "intel_gen: %s: %s\n", path, err);
    return rc;
}

int main(int argc, char **argv) {
    char err[IR_ERR];
    ir_snapshot_t s;
    if (argc == 4 && !strcmp(argv[1], "gen")) {
        ir_lock_t l;
        if (read_lock(argv[2], &l) != 0) return 1;
        if (ir_snapshot_load(argv[2], &s, err, sizeof(err)) != 0) {
            fprintf(stderr, "intel_gen: %s\n", err);
            return 1;
        }
        /* The lock names the snapshot it was written for: a pack file
         * changed by hand, or a LOCK edited by hand, stops the build. */
        if (strcmp(l.hash, s.hash) != 0) {
            fprintf(stderr, "intel_gen: %s/LOCK names snapshot %s, the packs hash to %s;"
                    " refresh with `make update-intel PACK=<dir>`\n", argv[2], l.hash, s.hash);
            ir_snapshot_free(&s);
            return 1;
        }
        int rc = gen(&s, &l, argv[3]);
        ir_snapshot_free(&s);
        free(g_buf);
        return rc ? 1 : 0;
    }
    if (argc == 6 && !strcmp(argv[1], "lock")) {
        ir_lock_t l;
        memset(&l, 0, sizeof(l));
        char text[512];
        snprintf(text, sizeof(text),
                 "pack_version: %s\nhash: %064d\ncomint_commit: %s\ndate: %s\n",
                 argv[3], 0, argv[4], argv[5]);
        if (ir_lock_parse(text, strlen(text), &l, err, sizeof(err)) != 0) {
            fprintf(stderr, "intel_gen: %s\n", err);
            return 1;
        }
        if (ir_snapshot_load(argv[2], &s, err, sizeof(err)) != 0) {
            fprintf(stderr, "intel_gen: %s\n", err);
            return 1;
        }
        char path[4096], tmp[4200];
        snprintf(path, sizeof(path), "%s/LOCK", argv[2]);
        snprintf(tmp, sizeof(tmp), "%s.tmp", path);
        FILE *f = fopen(tmp, "w");
        if (!f) { fprintf(stderr, "intel_gen: %s: %s\n", tmp, strerror(errno)); ir_snapshot_free(&s); return 1; }
        fprintf(f, "# The intel-pack snapshot this tree builds from (#231). Written by\n");
        fprintf(f, "# `make update-intel` (tools/intel_gen lock); never edited by hand:\n");
        fprintf(f, "# the build refuses a LOCK whose hash the packs do not hash to.\n");
        fprintf(f, "# hash: SHA-256 over \"<pack_name> <sha256 of its manifest.json>\\n\"\n");
        fprintf(f, "# for each pack below, in this order (docs/wiki/pack-schema.md).\n");
        fprintf(f, "pack_version: %s\n", l.pack_version);
        fprintf(f, "hash: %s\n", s.hash);
        fprintf(f, "comint_commit: %s\n", l.comint_commit);
        fprintf(f, "date: %s\n", l.date);
        fprintf(f, "packs:");
        for (int i = 0; i < IR_NPACKS; i++) fprintf(f, " %s", ir_pack_names[i]);
        fprintf(f, "\n");
        int ok = fclose(f) == 0;
        ir_snapshot_free(&s);
        if (!ok || rename(tmp, path) != 0) {
            fprintf(stderr, "intel_gen: cannot write %s\n", path);
            remove(tmp);
            return 1;
        }
        return 0;
    }
    fprintf(stderr, "usage: intel_gen gen INTEL_DIR OUT_DIR\n"
                    "       intel_gen lock INTEL_DIR VERSION COMMIT DATE\n");
    return 2;
}
